"""Evaluation client for Antigravity PreToolUse hook."""
import json
import os
import sys
import time
import urllib.request
import urllib.error
from pathlib import Path
from typing import Dict, Any, Tuple, Optional

from .cache import GuardCache, get_cache_key

# Default fallback settings
DEFAULT_HOST = "127.0.0.1"
DEFAULT_PORT = 8080
DEFAULT_THRESHOLD = 0.20
DEFAULT_TIMEOUT = 5.0
READ_ONLY_TOOLS = {
    "view_file",
    "list_dir",
    "grep_search",
    "search_web",
    "read_url_content",
    "read_resource",
    "list_resources",
}


def load_config() -> Dict[str, Any]:
    """Loads configuration from config.json if available, with env var overrides."""
    config_paths = [
        Path.cwd() / "config" / "config.json",
        Path(__file__).parent.parent / "config" / "config.json",
        Path.home() / ".gemini" / "config" / "antigravity-auto-mode.json",
        Path.home() / ".gemini" / "config" / "agy-shieldstral-guard.json",
    ]
    cfg = {}
    for p in config_paths:
        if p.exists():
            try:
                with open(p, "r", encoding="utf-8") as f:
                    cfg = json.load(f)
                    break
            except Exception:
                pass

    # Ensure nested dicts exist
    if "daemon" not in cfg:
        cfg["daemon"] = {}
    if "guard" not in cfg:
        cfg["guard"] = {}

    # Environment variable overrides
    if "AGY_GUARD_HOST" in os.environ:
        cfg["daemon"]["host"] = os.environ["AGY_GUARD_HOST"]
    if "AGY_GUARD_PORT" in os.environ:
        try:
            cfg["daemon"]["port"] = int(os.environ["AGY_GUARD_PORT"])
        except ValueError:
            pass
    if "AGY_GUARD_TIMEOUT" in os.environ:
        try:
            cfg["daemon"]["timeout_seconds"] = float(os.environ["AGY_GUARD_TIMEOUT"])
        except ValueError:
            pass
    if "AGY_GUARD_THRESHOLD" in os.environ:
        try:
            cfg["guard"]["unsafe_threshold"] = float(os.environ["AGY_GUARD_THRESHOLD"])
        except ValueError:
            pass
    if "AGY_GUARD_UNSAFE_DECISION" in os.environ:
        cfg["guard"]["unsafe_decision"] = os.environ["AGY_GUARD_UNSAFE_DECISION"]
    if "AGY_GUARD_FAIL_CLOSED_DECISION" in os.environ:
        cfg["guard"]["fail_closed_decision"] = os.environ["AGY_GUARD_FAIL_CLOSED_DECISION"]

    return cfg


def resolve_daemon_url(config: Optional[Dict[str, Any]] = None) -> str:
    """
    Resolves active daemon URL via environment variables, explicit config, dynamic endpoint.json files,
    or configured host/port fallback.
    """
    if "AGY_GUARD_URL" in os.environ:
        return os.environ["AGY_GUARD_URL"].rstrip("/")
    if "AGY_GUARD_PORT" in os.environ:
        host = os.environ.get("AGY_GUARD_HOST", DEFAULT_HOST)
        return f"http://{host}:{os.environ['AGY_GUARD_PORT']}"

    # If config explicitly specifies a non-zero, non-default port, honor it directly
    if config is not None:
        daemon_cfg = config.get("daemon", {})
        explicit_port = daemon_cfg.get("port")
        if explicit_port is not None and explicit_port != 0 and explicit_port != DEFAULT_PORT:
            host = daemon_cfg.get("host", DEFAULT_HOST)
            return f"http://{host}:{explicit_port}"

    # Search for endpoint discovery files generated by sidecar / daemon
    discovery_files = []
    if "ANTIGRAVITY_EXECUTABLE_DATA_DIR" in os.environ:
        discovery_files.append(Path(os.environ["ANTIGRAVITY_EXECUTABLE_DATA_DIR"]) / "endpoint.json")

    discovery_files.extend([
        Path.home() / ".gemini" / "antigravity" / "sidecar_data" / "antigravity-auto-mode" / "shieldstral-daemon" / "endpoint.json",
        Path.home() / ".gemini" / "antigravity" / "sidecar_data" / "antigravity-auto-mode" / "shieldstral-daemon" / "data" / "endpoint.json",
        Path.home() / ".gemini" / "antigravity" / "sidecar_data" / "agy-shieldstral-guard" / "shieldstral-daemon" / "endpoint.json",
        Path.home() / ".gemini" / "antigravity" / "sidecar_data" / "agy-shieldstral-guard" / "shieldstral-daemon" / "data" / "endpoint.json",
        Path(__file__).resolve().parent.parent / ".cache" / "endpoint.json",
        Path.home() / ".cache" / "antigravity_auto_mode_endpoint.json",
        Path.home() / ".cache" / "agy_shieldstral_guard_endpoint.json"
    ])

    for ep_file in discovery_files:
        if ep_file.exists():
            try:
                with open(ep_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    url = data.get("url")
                    if url:
                        return url.rstrip("/")
            except Exception:
                pass

    if config is None:
        config = load_config()

    daemon_cfg = config.get("daemon", {})
    host = daemon_cfg.get("host", DEFAULT_HOST)
    port = daemon_cfg.get("port", DEFAULT_PORT)
    if port == 0:
        port = DEFAULT_PORT
    return f"http://{host}:{port}"


def evaluate_tool_call(
    tool: str,
    args: Any,
    config: Optional[Dict[str, Any]] = None,
    cache: Optional[GuardCache] = None
) -> Tuple[str, str, float]:
    """
    Evaluates a tool call against the Shieldstral guardrail daemon.

    Returns:
        Tuple of (decision, reason, p_unsafe).
        Decision is 'allow' or 'ask'.
    """
    if config is None:
        config = load_config()

    daemon_cfg = config.get("daemon", {})
    guard_cfg = config.get("guard", {})

    timeout = daemon_cfg.get("timeout_seconds", DEFAULT_TIMEOUT)
    threshold = guard_cfg.get("unsafe_threshold", DEFAULT_THRESHOLD)
    bypass_read_only = guard_cfg.get("bypass_read_only_tools", False)
    read_only_list = set(guard_cfg.get("read_only_tools", []))

    # Fast Path 1: Optional non-destructive read-only tools (if explicitly enabled)
    if bypass_read_only and tool in read_only_list:
        return "allow", f"Auto-approved non-destructive read tool: {tool}", 0.0

    # Fast Path 2: Local SHA-256 Cache
    cache_enabled = guard_cfg.get("cache_enabled", True)
    cache_key = get_cache_key(tool, args)

    if cache is None and cache_enabled:
        cache_file = guard_cfg.get("cache_file")
        ttl = guard_cfg.get("cache_ttl_seconds", 86400)
        cache = GuardCache(cache_file=cache_file, ttl_seconds=ttl)

    if cache is not None and cache.is_safe(cache_key):
        return "allow", f"Auto-approved via safe cache: {tool}", 0.0

    # Path 3: Query Local Daemon (Dynamically Discovered Endpoint)
    base_url = resolve_daemon_url(config)
    endpoint = f"{base_url}/evaluate"
    payload = json.dumps({"tool": tool, "args": args}).encode("utf-8")
    req = urllib.request.Request(
        endpoint,
        data=payload,
        headers={"Content-Type": "application/json"}
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            p_unsafe = float(data.get("p_unsafe", 1.0))

        if p_unsafe < threshold:
            if cache is not None:
                cache.mark_safe(cache_key)
            return (
                "allow",
                f"Shieldstral: Safe execution approved (P(Unsafe)={p_unsafe:.2f} < {threshold:.2f})",
                p_unsafe
            )
        else:
            unsafe_decision = guard_cfg.get("unsafe_decision", "force_ask")
            return (
                unsafe_decision,
                f"Shieldstral: Potential safety violation detected (P(Unsafe)={p_unsafe:.2f} >= {threshold:.2f})",
                p_unsafe
            )

    except (urllib.error.URLError, TimeoutError, ConnectionRefusedError, Exception) as e:
        fail_decision = guard_cfg.get("fail_closed_decision", guard_cfg.get("unsafe_decision", "force_ask"))
        return (
            fail_decision,
            f"Shieldstral: Daemon unreachable or error ({type(e).__name__}). Requiring user confirmation (Fail-Closed).",
            1.0
        )


def _log_debug(
    response: dict,
    tool: str = "",
    args: Any = None,
    p_unsafe: Optional[float] = None,
    latency_ms: float = 0.0
):
    try:
        log_path = Path.home() / ".cache" / "agy_hook_debug.log"
        action = (args.get("CommandLine") or args.get("TargetFile") or args.get("AbsolutePath") or "") if isinstance(args, dict) else ""
        entry = {
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "tool": tool,
            "action": action,
            "decision": response.get("decision", ""),
            "p_unsafe": round(p_unsafe, 4) if p_unsafe is not None else None,
            "latency_ms": round(latency_ms, 2) if latency_ms > 0 else None,
            "reason": response.get("reason", "")
        }
        log_path.parent.mkdir(parents=True, exist_ok=True)
        if log_path.exists() and log_path.stat().st_size > 5 * 1024 * 1024:
            log_path.replace(log_path.with_suffix(".log.old"))
        with open(log_path, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except Exception:
        pass


def run_hook(stdin_data: Optional[str] = None) -> int:
    """
    Main hook execution pipeline parsing Antigravity PreToolUse JSON from stdin
    and writing decision JSON to stdout.

    Returns:
        0 (Always 0 for clean Antigravity 2.0 stdout parsing).
    """
    t0 = time.perf_counter()
    if stdin_data is None:
        try:
            line = sys.stdin.readline()
            if line.strip():
                try:
                    json.loads(line)
                    stdin_data = line
                except Exception:
                    remaining = sys.stdin.read()
                    stdin_data = line + remaining
            else:
                stdin_data = ""
        except Exception:
            stdin_data = ""

    if not stdin_data.strip():
        # Empty input: default allow
        response = {"decision": "allow", "reason": "Empty tool payload"}
        _log_debug(response, latency_ms=(time.perf_counter() - t0) * 1000)
        sys.stdout.write(json.dumps(response) + "\n")
        return 0

    try:
        payload = json.loads(stdin_data)
    except Exception:
        # Malformed input: fail-closed
        response = {"decision": "force_ask", "reason": "Malformed JSON input payload"}
        _log_debug(response, latency_ms=(time.perf_counter() - t0) * 1000)
        sys.stdout.write(json.dumps(response) + "\n")
        return 0

    # Extract tool call from Antigravity PreToolUse schema or raw schema
    if "toolCall" in payload:
        tool_call = payload.get("toolCall", {})
        tool = tool_call.get("name", "")
        args = tool_call.get("args", {})
    else:
        tool = payload.get("tool", "")
        args = payload.get("args", {})

    decision, reason, p_unsafe = evaluate_tool_call(tool, args)

    response = {
        "decision": decision,
        "reason": reason
    }

    _log_debug(
        response=response,
        tool=tool,
        args=args,
        p_unsafe=p_unsafe,
        latency_ms=(time.perf_counter() - t0) * 1000
    )

    sys.stdout.write(json.dumps(response) + "\n")
    sys.stdout.flush()

    if decision != "allow":
        print(f"[Shieldstral Gate] {reason}", file=sys.stderr)
    return 0
